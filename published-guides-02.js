const escape = value => String(value ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
function renderBody(guide) {
  return guide.sections.map((section, i) => {
    const citations = section.citations.map(n => {
      const source = guide.sources[n - 1];
      if (!source || !source.url.startsWith('https://')) throw new TypeError('Invalid published source');
      return `<a class="citation-link" href="${escape(source.url)}" target="_blank" rel="noopener noreferrer" aria-label="Source ${n}: ${escape(source.name)}">[${n}]</a>`;
    }).join(' ');
    return `<h2 id="section-${i + 1}">${escape(section.heading)}</h2>` +
      section.paragraphs.map(paragraph => `<p>${escape(paragraph)}</p>`).join('') +
      `<p class="section-citations"><span class="fine">Supporting sources:</span> ${citations}</p>`;
  }).join('');
}
